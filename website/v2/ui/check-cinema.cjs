const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'night.html'), 'utf8');
const source = fs.readFileSync(path.join(root, 'cinema-story.js'), 'utf8');
const tick = () => new Promise(r => setTimeout(r, 35));
async function setup({ reduce=false, compact=false, hash='', partial=false }={}) {
  const dom = new JSDOM(html, {url:'file://' + root + '/night.html'+hash,runScripts:'outside-only',pretendToBeVisual:true});
  const w=dom.window,d=w.document, media=[];
  const state={reduce,compact,top:76,scrolls:[],seeks:[],loads:0,visible:false};
  w.matchMedia=query=>{const m={get matches(){return query.includes('reduced')?state.reduce:state.compact;},addEventListener(type,fn){media.push(fn);}};return m;};
  let observer;
  w.IntersectionObserver=class {constructor(cb){observer=cb;}observe(){}disconnect(){}};
  const film=d.querySelector('video'),track=d.querySelector('.cinema-track'),stage=d.querySelector('.cinema-stage');
  film.dataset.renderedFrames=partial?'56':'96';
  track.getBoundingClientRect=()=>({top:state.top});
  Object.defineProperty(track,'offsetHeight',{value:3000});Object.defineProperty(stage,'offsetHeight',{value:800});
  d.querySelector('.site-header').getBoundingClientRect=()=>({height:76});
  w.scrollTo=options=>{state.scrolls.push(options);};
  w.HTMLElement.prototype.scrollIntoView=function(){};
  let time=0,seeking=false;
  Object.defineProperty(film,'duration',{get:()=>partial?56/24:4});
  Object.defineProperty(film,'seeking',{get:()=>seeking});
  Object.defineProperty(film,'currentTime',{get:()=>time,set:v=>{state.seeks.push(v);time=v;seeking=true;w.setTimeout(()=>{seeking=false;film.dispatchEvent(new w.Event('seeked'));},0);}});
  film.load=()=>{state.loads++;};film.pause=()=>{};
  w.eval(source);await tick();
  return {dom,w,d,film,state,media,intersect:()=>observer([{isIntersecting:true}])};
}
(async()=>{
  const a=await setup();const {d,w,film,state}=a;
  assert(d.querySelector('.cinema-story').classList.contains('is-ready'));
  assert.equal(d.querySelectorAll('.cinema-chapter:not([hidden])').length,1);
  assert(!film.hasAttribute('src'),'film must not load above the fold');
  a.intersect();assert.equal(film.getAttribute('src'),'assets/cairn-story.mp4');assert.equal(film.preload,'auto');
  film.dispatchEvent(new w.Event('loadeddata'));await tick();
  state.top=76-2200*(2/3);w.dispatchEvent(new w.Event('scroll'));await tick();await tick();
  assert.equal(d.querySelector('.cinema-story').dataset.chapter,'2');
  assert.equal(d.querySelector('[data-cinema-step="2"]').getAttribute('aria-pressed'),'true');
  assert(Math.abs(film.currentTime-(4-1/24)*2/3)<.01,'scroll maps to protection keyframe');
  state.top=76-2200;w.dispatchEvent(new w.Event('scroll'));await tick();await tick();
  assert(film.currentTime<4,'last step must not seek beyond the final frame');
  const button=d.querySelector('[data-cinema-step="1"]');button.click();
  assert.equal(state.scrolls.at(-1).behavior,'smooth');
  film.dispatchEvent(new w.Event('error'));assert(!d.querySelector('.cinema-story').classList.contains('has-film'));
  state.top=76;w.dispatchEvent(new w.Event('scroll'));await tick();
  assert.equal(d.querySelector('.cinema-poster').getAttribute('src'),'assets/cairn-story-understand.jpg');
  for(const id of ['changes','make-room','review','outcome'])assert.equal(d.querySelectorAll('#'+id).length,1);
  assert(!d.querySelector('.process-canvas'));
  a.dom.window.close();

  const partial=await setup({partial:true});partial.intersect();
  partial.film.dispatchEvent(new partial.w.Event('loadeddata'));await tick();
  partial.state.top=76-2200*(2/3);partial.w.dispatchEvent(new partial.w.Event('scroll'));await tick();
  assert.equal(partial.d.querySelector('.cinema-story').dataset.chapter,'2');
  assert(!partial.d.querySelector('.cinema-story').classList.contains('has-film'),'unrendered chapters show their still');
  assert(partial.state.seeks.every(t=>t<=55/24),'partial film must never seek beyond rendered frames');
  partial.state.top=76-2200/3;partial.w.dispatchEvent(new partial.w.Event('scroll'));await tick();await tick();
  assert(partial.d.querySelector('.cinema-story').classList.contains('has-film'),'returning to rendered chapters restores video');
  assert(Math.abs(partial.film.currentTime-95/72)<.01,'partial export retains full timeline timing');
  partial.dom.window.close();

  const b=await setup({reduce:true});b.intersect();assert(!b.film.hasAttribute('src'));
  b.d.querySelector('[data-cinema-step="2"]').click();
  assert.equal(b.d.querySelector('.cinema-story').dataset.chapter,'2');
  assert.equal(b.d.querySelector('.cinema-poster').getAttribute('src'),'assets/cairn-story-protect.jpg');
  const end=b.d.querySelector('[data-cinema-step="2"]');
  end.dispatchEvent(new b.w.KeyboardEvent('keydown',{key:'End',bubbles:true,cancelable:true}));
  assert.equal(b.d.activeElement.dataset.cinemaStep,'3');
  assert.equal(b.d.querySelector('.cinema-status').textContent,'Step 4 of 4: Verify');
  assert.equal(b.state.seeks.length,0,'reduced motion never scrubs video');
  assert.equal(b.state.scrolls.length,0,'manual chapter controls do not force page scrolling');
  b.dom.window.close();

  const c=await setup({compact:true,hash:'#outcome'});
  assert.equal(c.d.querySelector('.cinema-story').dataset.chapter,'3');
  c.d.querySelector('[data-cinema-step="0"]').click();assert.equal(c.d.querySelector('.cinema-story').dataset.chapter,'0');
  c.film.dispatchEvent(new c.w.Event('loadeddata'));c.d.querySelector('[data-cinema-step="2"]').click();
  c.state.reduce=true;c.media.forEach(fn=>fn());await tick();
  assert(!c.film.hasAttribute('src'),'enabling reduced motion unloads the film');
  c.dom.window.close();
  console.log('Cinema checks passed: lazy media, scroll mapping, seek bounds, chapters, keyboard, reduced motion, deep links and media-error fallback.');
})().catch(error=>{console.error(error.message);process.exit(1);});
